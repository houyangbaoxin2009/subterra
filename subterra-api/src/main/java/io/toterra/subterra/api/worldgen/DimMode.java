package io.toterra.subterra.api.worldgen;

import java.util.Locale;
import java.util.Objects;

/**
 * p.2.36.2 九维能力位（capability level）的三种模式（纯 JDK、确定性）：每一维在
 * {@link WorldgenProfile} 里各占一个能力位，决定该维如何参与世界生成。
 * <ul>
 *   <li>{@link #ENABLE}——该维由 Subterra 自有管线生成（缺省，全部九维均为 ENABLE）。</li>
 *   <li>{@link #DISABLE}——该维回退 vanilla 对应机制（零行为变化，用于对照与降级）。</li>
 *   <li>{@link #REDIRECT}——该维改由 {@code target}（{@code namespace:path}）指向的自有实现或
 *       域模组实现生成；目标由消费方注册，引擎不预置任何目标。</li>
 * </ul>
 * 解析（{@link #parse}）宽容别名（{@code on/off/1/0}），渲染（{@link #id()}）只有规范小写名
 * ——解析多对一、渲染一对一，保证 td 往返稳定。
 * <p>
 * p.2.36.2 the three modes of a nine-dimension capability bit (pure JDK, deterministic). Each dimension
 * owns one capability bit in {@link WorldgenProfile}: {@link #ENABLE} (generated by the Subterra pipeline;
 * the default for all nine), {@link #DISABLE} (falls back to the vanilla mechanism — zero behaviour change,
 * for A/B and degradation) and {@link #REDIRECT} (generated by the implementation named by {@code target},
 * a {@code namespace:path} registered by consumers; the engine presets no targets). Parsing accepts aliases
 * ({@code on/off/1/0}); rendering emits only the canonical lowercase id — many-to-one on parse, one-to-one
 * on render, so td round-trips are stable.
 */
public enum DimMode {

    /** The dimension is generated by the Subterra pipeline (default). /
     *  该维由 Subterra 自有管线生成（缺省）。 */
    ENABLE,

    /** The dimension falls back to its vanilla mechanism (zero behaviour change). /
     *  该维回退 vanilla 对应机制（零行为变化）。 */
    DISABLE,

    /** The dimension is generated by the implementation named by the redirect target. /
     *  该维由重定向目标所指的实现生成。 */
    REDIRECT;

    /** The canonical lowercase id used by td rendering ({@code enable} / {@code disable} /
     *  {@code redirect}). / td 渲染用的规范小写名（{@code enable} / {@code disable} / {@code redirect}）。 */
    public String id() {
        return name().toLowerCase(Locale.ROOT);
    }

    /**
     * Parses a td value into a mode (trim + lowercase, aliases {@code on/1} and {@code off/0}
     * accepted); anything else is rejected deterministically. /
     * 解析 td 值为模式（trim + 小写，接受 {@code on/1} 与 {@code off/0} 别名），其余确定性拒绝。
     *
     * @param value the td value (non-null).
     * @return the parsed mode.
     * @throws NullPointerException     if {@code value} is null.
     * @throws IllegalArgumentException if the value names no known mode.
     */
    public static DimMode parse(String value) {
        Objects.requireNonNull(value, "dim mode must not be null");
        return switch (value.trim().toLowerCase(Locale.ROOT)) {
            case "enable", "on", "1" -> ENABLE;
            case "disable", "off", "0" -> DISABLE;
            case "redirect" -> REDIRECT;
            default -> throw new IllegalArgumentException("unknown dim mode '" + value + "'");
        };
    }
}
